# Separa el string en una lista de strings de menos de 127 columnas
def split_string (string, fuente): 
    columns = 1
    words = string.split() # Separo en cada espacio.
    fila = []
    contenido_de_la_Fila = []
    for word in words: # Para cada palabra:
        # A las columnas actuales les sumo las columnas que requiere la siguiente palabra. 
        columns = columns + sum([len(fuente.get(char, [0xFF] * 4)) for char in word])
        if columns < 127:
            contenido_de_la_Fila.append(word)
        else:
            fila.append(" ".join(contenido_de_la_Fila))
            contenido_de_la_Fila=[]
            contenido_de_la_Fila.append(word)
            columns=sum([len(fuente.get(char, [0xFF] * 4)) for char in word])

        # Por cada palabra, tambien le sumo a las columnas el caracter espacio " " que va al final...
        columns = columns + len(fuente.get(" ", [0xFF] * 4))
        
    fila.append(" ".join(contenido_de_la_Fila))
    anchos = [sum(len(fuente.get(char, [0xFF] * 4)) for char in linea) for linea in fila]
    
    return fila, anchos
    

