def fill_display():
    for page in range(8):  # 8 páginas en una pantalla de 64px de alto
        send_command(0xB0 + page)  # Selecciona la página
        send_command(0x00)  # Dirección columna baja
        send_command(0x10)  # Dirección columna alta
        for _ in range(128):  # 128 columnas en una pantalla de 128px de ancho
            bus.write_byte_data(display, 0x40, 0xFF)  # Enviar datos (todos los bits encendidos)

